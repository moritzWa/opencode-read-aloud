import { fileURLToPath } from "node:url"

// Keep the upstream algorithm and scores, but ship only English/German model data.
// The normal medium entrypoint loads all 60 languages into every TUI process.
const entry = import.meta.resolve("eld")
const { ngramsData } = await import(new URL("../ngrams/medium.js", entry).href)
const selected = Object.entries(ngramsData.languages).filter(([, code]) => code === "en" || code === "de")
const languages = Object.fromEntries(selected.map(([, code], index) => [index, code]))
const identifiers = Object.fromEntries(selected.map(([id], index) => [id, index]))
const ngrams = Object.fromEntries(
  Object.entries(ngramsData.ngrams).flatMap(([gram, scores]) => {
    const subset = Object.fromEntries(
      Object.entries(scores as Record<string, number>)
        .filter(([id]) => id in identifiers)
        .map(([id, score]) => [identifiers[id], score]),
    )
    return Object.keys(subset).length ? [[gram, subset]] : []
  }),
)
const model = { type: ngramsData.type, languages, ngrams, isSubset: true }
const result = await Bun.build({
  entrypoints: ["eld-english-german"],
  target: "bun",
  minify: true,
  plugins: [
    {
      name: "english-german-model",
      setup(build) {
        build.onResolve({ filter: /^eld-english-german$/ }, () => ({ path: "entry", namespace: "model" }))
        build.onLoad({ filter: /.*/, namespace: "model" }, () => ({
          loader: "js",
          contents: `import { createEld } from ${JSON.stringify(fileURLToPath(new URL("../languageDetector.js", entry)))};
const {instance,loadData}=createEld();loadData(${JSON.stringify(model)});export const detector=instance;`,
        }))
      },
    },
  ],
})
if (!result.success) throw new AggregateError(result.logs, "Detector build failed")
const header =
  "// Generated by tools/build-detector.ts from eld 2.1.1 (medium, English/German only).\n// Copyright 2023-2025 Nito T.M. Licensed under Apache-2.0; see detector.LICENSE.\n"
await Bun.write(new URL("../detector.js", import.meta.url), header + (await result.outputs[0].text()))
await Bun.write(new URL("../detector.LICENSE", import.meta.url), Bun.file(new URL("../../LICENSE", entry)))
console.log("Generated English/German detector:", Object.keys(ngrams).length, "ngrams")
